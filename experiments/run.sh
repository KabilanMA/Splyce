#!/usr/bin/env bash
# run.sh — Single entry point to run every experiment under experiments/.
#
# Two kinds of experiment are supported, chosen per-name via
# REALWORLD_EXPERIMENTS below:
#
# Synthetic-data experiments (the default kind) — for each one, this:
#   1. Generates that experiment's tensor data (gen_data.sh <experiment>)
#   2. Compiles it (<experiment>/compile.sh)
#   3. Runs it (<experiment>/run.sh --clean), which executes every compiled
#      binary, then deletes the compiled binaries.
#   4. Deletes the tensor data generated in step 1 (tensor_*.tns), since it
#      can always be regenerated by gen_data.sh on the next run.
#
# Real-world-data experiments (speedups/real_world_data/<kernel>/) — for
# each one, this instead:
#   1. Compiles it (<experiment>/compile.sh).
#   2. Runs its curated benchmark (<experiment>/run_suitesparse_benchmark.py),
#      which downloads the real SuiteSparse matrix/matrices it needs,
#      generates any synthetic operand(s) it pairs them with, runs both the
#      scf baseline and Splyce phase_001 binaries, appends to its own
#      <kernel>_realworld_results.csv / _raw_runtimes.csv (in its own
#      directory — kept, since that's the actual benchmark output), and
#      already deletes its own tensor_*.tns/benchmark and the downloaded
#      suitesparse/<name>/ director(y/ies) internally once it's done.
#   3. Deletes the compiled binaries (test_benchmark_*) — the one artifact
#      run_suitesparse_benchmark.py doesn't already clean up itself.
#   Before the first such experiment, this also runs
#   suitesparse/scrape_metadata.py once if matrix_metadata.json doesn't
#   exist yet, since every kernel's run_suitesparse_benchmark.py needs it
#   to look up download URLs.
#
# The five spgemm/spmmh/spmspv/spmttkrp/spttspm "_speedup" experiments are
# the synthetic-data speedup kernels (experiments/speedups/synthetic_data/
# <kernel>/) — each compiles a plain mlir-opt --sparsifier baseline (no
# Splyce vectorization) plus the single Splyce phase-001 binary, runs both,
# and writes its own results.csv (in its own directory) — one row per
# configuration. speedups/synthetic_data/print_speedup_summary.py then
# reads every kernel's results.csv and prints one combined table (kernel,
# baseline time, Splyce time, speedup). phase_ablation instead writes its
# own richer TMA breakdown (phase_ablation/tma_results.csv), multicore its
# own core-count scaling results (multicore/results.csv), sparsity_scaling
# its own density-sweep results (sparsity_scaling/results.csv), and
# vector_width its own vector-width-sweep results (vector_width/results.csv)
# — see each one's own run.sh.
#
# The five spgemm/spmmh/spmspv/spmttkrp/spttspm "_realworld" experiments
# are the real-world-data kernels (experiments/speedups/real_world_data/
# <kernel>/) described above — each is a single curated real (+ synthetic,
# where noted) matrix pairing rather than a parameter sweep: spgemm_realworld
# (bcsstm35/exdata_1/heart1 each squared against themselves, plus
# c8_mat11 x a 9.37%-dense synthetic), spmmh_realworld (bayer01 for B and D,
# a fully-dense synthetic C), spmspv_realworld (stokes for B, a
# 0.001%-dense synthetic vector x), spmttkrp_realworld (heart1 for D,
# 10.97%-dense synthetic B/C), and spttspm_realworld (barth4/Nasa for C, a
# 0.06%-dense synthetic B) — see each one's own run_suitesparse_benchmark.py
# for exact shapes/densities.
#
# Add new experiment names to ALL_EXPERIMENTS (and their directory in
# EXPERIMENT_DIR) as they're set up — each synthetic-data experiment needs
# a compile.sh, a run.sh, and a matching generator in gen_data.c; each
# real-world-data experiment needs a compile.sh and a
# run_suitesparse_benchmark.py, and its name added to
# REALWORLD_EXPERIMENTS below.
#
# Usage:
#   ./run.sh all                  # every experiment in ALL_EXPERIMENTS
#   ./run.sh table2                # the 5 synthetic-data "_speedup" kernels,
#                                   # then prints the combined speedup table
#                                   # (speedups/synthetic_data/print_speedup_
#                                   # summary.py) once all 5 have finished
#   ./run.sh realdata               # the 5 real-world-data "_realworld" kernels,
#                                   # then prints the combined results table
#                                   # (speedups/real_world_data/print_
#                                   # realworld_summary.py) once all 5 have
#                                   # finished
#   ./run.sh <experiment> [...]    # one or more individual experiments by name
#                                   # (e.g. ./run.sh phase_ablation, or
#                                   # ./run.sh spgemm_speedup spmspv_speedup)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

ALL_EXPERIMENTS=(
  phase_ablation
  multicore
  sparsity_scaling
  vector_width

  spgemm_speedup
  spmspv_speedup
  spmttkrp_speedup
  spmmh_speedup
  spttspm_speedup

  spgemm_realworld
  spmspv_realworld
  spmttkrp_realworld
  spmmh_realworld
  spttspm_realworld
)

declare -A EXPERIMENT_DIR=(
  [phase_ablation]="phase_ablation"
  [multicore]="multicore"
  [sparsity_scaling]="sparsity_scaling"
  [vector_width]="vector_width"
  [spgemm_speedup]="speedups/synthetic_data/spgemm"
  [spmmh_speedup]="speedups/synthetic_data/spmmh"
  [spmspv_speedup]="speedups/synthetic_data/spmspv"
  [spmttkrp_speedup]="speedups/synthetic_data/spmttkrp"
  [spttspm_speedup]="speedups/synthetic_data/spttspm"
  [spgemm_realworld]="speedups/real_world_data/spgemm"
  [spmmh_realworld]="speedups/real_world_data/spmmh"
  [spmspv_realworld]="speedups/real_world_data/spmspv"
  [spmttkrp_realworld]="speedups/real_world_data/spmttkrp"
  [spttspm_realworld]="speedups/real_world_data/spttspm"
)

# "table2" run.sh target: the five synthetic-data speedup kernels.
TABLE2_EXPERIMENTS=(
  spgemm_speedup
  spmspv_speedup
  spmttkrp_speedup
  spmmh_speedup
  spttspm_speedup
)

# "realdata" run.sh target: the five real-world-data kernels.
REALDATA_EXPERIMENTS=(
  spgemm_realworld
  spmspv_realworld
  spmttkrp_realworld
  spmmh_realworld
  spttspm_realworld
)

usage() {
  echo "Usage: $0 all|table2|realdata|<experiment> [<experiment> ...]" >&2
  echo "  all                 - run every experiment" >&2
  echo "  table2              - run ${TABLE2_EXPERIMENTS[*]}" >&2
  echo "  realdata            - run ${REALDATA_EXPERIMENTS[*]}" >&2
  echo "  <experiment> [...]  - run one or more individual experiments by name" >&2
  echo "Available experiments: ${ALL_EXPERIMENTS[*]}" >&2
  exit 1
}

if [[ $# -eq 0 ]]; then
  usage
fi

RUN_MODE="$1"

case "$1" in
  all)
    EXPERIMENTS=("${ALL_EXPERIMENTS[@]}")
    ;;
  table2)
    EXPERIMENTS=("${TABLE2_EXPERIMENTS[@]}")
    ;;
  realdata)
    EXPERIMENTS=("${REALDATA_EXPERIMENTS[@]}")
    ;;
  *)
    EXPERIMENTS=("$@")
    for experiment in "${EXPERIMENTS[@]}"; do
      if [[ -z "${EXPERIMENT_DIR[$experiment]+x}" ]]; then
        echo "error: unknown experiment '$experiment'" >&2
        usage
      fi
    done
    ;;
esac

# Experiment names driven by run_suitesparse_benchmark.py (compile.sh +
# a curated real/synthetic matrix pairing) instead of gen_data.sh + run.sh.
REALWORLD_EXPERIMENTS=(
  spgemm_realworld
  spmmh_realworld
  spmspv_realworld
  spmttkrp_realworld
  spttspm_realworld
)

is_realworld() {
  local name="$1"
  for rw in "${REALWORLD_EXPERIMENTS[@]}"; do
    [[ "$rw" == "$name" ]] && return 0
  done
  return 1
}

SUITESPARSE_DIR="$SCRIPT_DIR/speedups/real_world_data/suitesparse"
SUITESPARSE_METADATA="$SUITESPARSE_DIR/matrix_metadata.json"

for experiment in "${EXPERIMENTS[@]}"; do
  exp_dir="$SCRIPT_DIR/${EXPERIMENT_DIR[$experiment]}"

  echo "========================================"
  echo " Experiment: $experiment"
  echo "========================================"

  if is_realworld "$experiment"; then
    if [[ ! -f "$SUITESPARSE_METADATA" ]]; then
      echo "[$experiment] matrix_metadata.json not found — scraping SuiteSparse metadata (one-time) ..."
      ( cd "$SUITESPARSE_DIR" && ./scrape_metadata.py )
    fi

    echo "[$experiment] Compiling ..."
    ( cd "$exp_dir" && ./compile.sh )

    echo "[$experiment] Downloading real-world data and running ..."
    ( cd "$exp_dir" && ./run_suitesparse_benchmark.py --timeout 100000)

    echo "[$experiment] Deleting compiled binaries ..."
    rm -f "$exp_dir"/test_benchmark_*
    # tensor_*.tns, benchmark, and the downloaded suitesparse/<name>/
    # director(y/ies) are already deleted by run_suitesparse_benchmark.py
    # itself as each job finishes — this only needs to catch anything left
    # behind by a run that was interrupted before its own cleanup ran.
    rm -f "$exp_dir"/tensor_*.tns "$exp_dir"/benchmark

    echo "[$experiment] Done. Results in $exp_dir"
  else
    echo "[$experiment] Generating tensor data ..."
    "$SCRIPT_DIR/gen_data.sh" "$experiment"

    echo "[$experiment] Compiling ..."
    ( cd "$exp_dir" && ./compile.sh )

    echo "[$experiment] Running ..."
    ( cd "$exp_dir" && ./run.sh --clean )

    echo "[$experiment] Deleting tensor data ..."
    rm -f "$exp_dir"/tensor_*.tns

    echo "[$experiment] Done. Results in $exp_dir"
  fi
  echo ""
done

if [[ "$RUN_MODE" == "table2" ]]; then
  echo "========================================"
  echo " Table 2 summary"
  echo "========================================"
  "$SCRIPT_DIR/speedups/synthetic_data/print_speedup_summary.py"
fi

if [[ "$RUN_MODE" == "realdata" ]]; then
  echo "========================================"
  echo " Real-world data summary"
  echo "========================================"
  "$SCRIPT_DIR/speedups/real_world_data/print_realworld_summary.py"
fi
