#!/usr/bin/env python3
# run_suitesparse_benchmark.py — Real-world SpMMH benchmark, single curated
# matrix.
#
# Runs one fixed job (instead of sweeping the full 169 median-per-group
# SuiteSparse sample — see suitesparse/download_data.py for that sweep):
#
#   bayer01 (Grund, chemical process simulation): 57735 x 57735 square,
#   nnz=275094 (0.00825% dense) — the sparsest of the ten bayer0X matrices
#   in its group, chosen because A = D .* (B @ C) needs a dense
#   num_rows(B) x num_cols(D) output buffer, and bayer01 is the sparsest
#   member of the family whose implied dense buffers (A and C, see below)
#   still fit comfortably in 100 GB of RAM (2 * 57735^2 * 8 = 49.7 GiB).
#
#   Used for BOTH tensor_B and tensor_D (i.e. this benchmarks
#   A = B .* (B @ C)). tensor_C is a synthetically generated, fully
#   enumerated *dense* 57735 x 57735 tensor — matching bayer01's own square
#   dimension so B/C/D/A all conform — generated by generate_dense_2d_tns
#   below (ported from experiments/gen_data.py's function of the same
#   name). This differs from the old 169-dataset sweep's approach of
#   copying the same sparse .tns into tensor_C's file (relying on
#   sparse_tensor.new zero-filling missing coordinates against a
#   dense-declared encoding): here tensor_C is a real, fully-populated
#   dense tensor on disk.
#
# For this job, this script:
#   1. Downloads bayer01 (suitesparse/download_data.py's
#      download_and_extract, looked up via matrix_metadata.json — run
#      suitesparse/scrape_metadata.py first if that file doesn't exist yet).
#   2. Converts it to .tns (suitesparse/convert_to_tns.py's process_dir —
#      mirrors symmetric entries, drops explicit zeros) and copies it into
#      this directory as BOTH tensor_B.tns and tensor_D.tns.
#   3. Generates tensor_C.tns as a dense 57735 x 57735 tensor via
#      generate_dense_2d_tns.
#   4. Before doing any of the above, estimates peak memory and skips the
#      job outright if that exceeds --memory-limit-gb (default 250,
#      matching this benchmark's server). Both A (the output) and C
#      (synthetic, fully dense) are num_rows(B) x num_rows(B) dense f64
#      buffers (bayer01 is square), so the estimate is
#      2 * num_rows**2 * 8 bytes. There is no sparse-output binary for
#      spmmh (unlike spgemm): an attempt to make A a sparse CSC output was
#      found to compile and compute correctly, but the workspace-insertion
#      pattern it requires isn't recognized by Splyce's current vectorizer,
#      so skipping outright is the only available mitigation here rather
#      than swapping formats.
#   5. Runs test_benchmark_spmmh_splyce_phase_001 FIRST, then
#      test_benchmark_spmmh_scf — but only if Splyce didn't time out. If
#      Splyce already hit the timeout, the (unvectorized, typically no
#      faster) baseline is skipped entirely rather than wasting the same
#      timeout on a run that's essentially guaranteed to also be too slow.
#      Each binary loops 6 iterations internally per spmmh_dn.mlir's
#      @main, writing a "benchmark" file with one time per line.
#   6. Appends one summary row (dataset, group, nnz, scf_median,
#      splyce_median — median of the 5 non-cold-start iterations; scf_
#      median is "SKIPPED" when Splyce timed out, and both are
#      "SKIPPED_MEMORY" when the job was skipped per step 4 above) to
#      spmmh_realworld_results.csv, and every individual raw iteration
#      time to spmmh_realworld_raw_runtimes.csv as a backup.
#   7. Deletes tensor_B.tns/tensor_C.tns/tensor_D.tns and the downloaded/
#      converted suitesparse/bayer01/ directory afterward.
#
# Both CSVs are appended to, not overwritten, so a re-run is a no-op once
# bayer01 is already recorded (unless the CSV row is removed first).
#
# Prerequisite: ./compile.sh has already been run, so
# test_benchmark_spmmh_scf and test_benchmark_spmmh_splyce_phase_001
# exist in this directory.
#
# Usage:
#   ./run_suitesparse_benchmark.py
#   ./run_suitesparse_benchmark.py --timeout 600  # per-binary-run timeout
#                                                  # in seconds (default 300)
#   ./run_suitesparse_benchmark.py --memory-limit-gb 500  # override the
#                                                  # 250 GiB skip threshold

import csv
import os
import random
import shutil
import statistics
import subprocess
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SUITESPARSE_DIR = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "suitesparse"))
sys.path.insert(0, SUITESPARSE_DIR)

import download_data as dl  # noqa: E402
import convert_to_tns as cvt  # noqa: E402

BASELINE_BIN = os.path.join(SCRIPT_DIR, "test_benchmark_spmmh_scf")
SPLYCE_BIN = os.path.join(SCRIPT_DIR, "test_benchmark_spmmh_splyce_phase_001")

SUMMARY_CSV = os.path.join(SCRIPT_DIR, "spmmh_realworld_results.csv")
RAW_BACKUP_CSV = os.path.join(SCRIPT_DIR, "spmmh_realworld_raw_runtimes.csv")

TENSOR_B = os.path.join(SCRIPT_DIR, "tensor_B.tns")
TENSOR_C = os.path.join(SCRIPT_DIR, "tensor_C.tns")
TENSOR_D = os.path.join(SCRIPT_DIR, "tensor_D.tns")
BENCHMARK_FILE = os.path.join(SCRIPT_DIR, "benchmark")

# spmmh has no sparse-output binary (see module docstring), so an oversized
# job can only be skipped outright, not routed to a smaller-footprint
# variant. Default matches this benchmark's server RAM.
DEFAULT_MEMORY_LIMIT_GB = 250

# The single curated job this script runs — see module docstring for why
# bayer01 was chosen.
MATRIX_NAME = "bayer01"


def generate_dense_2d_tns(filename, rows, cols):
    # Ported from experiments/gen_data.py's generate_dense_2d_tns: writes
    # every (row, col) coordinate explicitly, i.e. a fully enumerated dense
    # tensor in FROSTT format.
    nnz = rows * cols

    with open(filename, "w") as f:
        f.write("# extended FROSTT format\n")
        f.write(f"2 {nnz}\n")
        f.write(f"{rows} {cols}\n")
        for r in range(1, rows + 1):
            for c in range(1, cols + 1):
                val = random.uniform(0.5, 2.5)
                f.write(f"{r} {c} {val:.4f}\n")

    print(f"Generated dense tensor: {filename} | Shape: ({rows}, {cols}) | NNZ: {nnz}")


def median_excl_first(times):
    rest = times[1:]
    return statistics.median(rest) if rest else None


def estimated_memory_bytes(entry):
    # A (the output) and C (synthetic, fully dense — see module docstring)
    # are both num_rows x num_rows dense f64 buffers (bayer01 is square); B
    # and D stay sparse (O(nnz), negligible next to the O(n^2) terms here).
    n = entry["num_rows"]
    return 2 * n * n * 8


def run_binary(bin_path, timeout):
    if os.path.isfile(BENCHMARK_FILE):
        os.remove(BENCHMARK_FILE)
    try:
        subprocess.run(
            [bin_path],
            cwd=SCRIPT_DIR,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        print(f"    [timeout] {os.path.basename(bin_path)} exceeded {timeout}s")
        return None, True
    if not os.path.isfile(BENCHMARK_FILE):
        print(f"    [warning] {os.path.basename(bin_path)} produced no benchmark file (likely crashed)")
        return None, False
    with open(BENCHMARK_FILE) as f:
        times = [float(line.strip()) for line in f if line.strip()]
    os.remove(BENCHMARK_FILE)
    return times, False


def already_recorded():
    if not os.path.isfile(SUMMARY_CSV):
        return set()
    with open(SUMMARY_CSV) as f:
        return {row["dataset"] for row in csv.DictReader(f)}


def main():
    args = sys.argv[1:]
    timeout = 300
    memory_limit_gb = DEFAULT_MEMORY_LIMIT_GB
    if "--timeout" in args:
        timeout = int(args[args.index("--timeout") + 1])
    if "--memory-limit-gb" in args:
        memory_limit_gb = float(args[args.index("--memory-limit-gb") + 1])
    memory_limit_bytes = memory_limit_gb * 1024 ** 3

    if not (os.path.isfile(BASELINE_BIN) and os.path.isfile(SPLYCE_BIN)):
        sys.exit("error: binaries not found — run ./compile.sh first")

    metadata = dl.load_metadata()
    entry = metadata.get(MATRIX_NAME)
    if entry is None:
        sys.exit(f"error: {MATRIX_NAME} not found in matrix_metadata.json")
    name, group = entry["name"], entry["group"]

    done = already_recorded()
    if name in done:
        print(f"{name} already recorded — nothing to do")
        return

    write_summary_header = not os.path.isfile(SUMMARY_CSV)
    write_raw_header = not os.path.isfile(RAW_BACKUP_CSV)

    with open(SUMMARY_CSV, "a", newline="") as sf, open(RAW_BACKUP_CSV, "a", newline="") as rf:
        summary_writer = csv.writer(sf)
        raw_writer = csv.writer(rf)
        if write_summary_header:
            summary_writer.writerow(["dataset", "group", "nnz", "scf_median_s", "splyce_median_s"])
        if write_raw_header:
            raw_writer.writerow(["dataset", "config", "iteration", "time_s"])

        print(f"=== {group}/{name} (nnz={entry['nnz']}) ===")

        est_bytes = estimated_memory_bytes(entry)
        if est_bytes > memory_limit_bytes:
            print(f"  [skip] {name}: estimated {est_bytes / 1024**3:.1f} GiB "
                  f"(> {memory_limit_gb:.0f} GiB memory limit) — no sparse-output "
                  f"binary for spmmh to fall back to, skipping")
            summary_writer.writerow([name, group, entry["nnz"], "SKIPPED_MEMORY", "SKIPPED_MEMORY"])
            sf.flush()
            print(f"Done. Summary: {SUMMARY_CSV}")
            return

        dataset_dir = os.path.join(SUITESPARSE_DIR, name)

        try:
            dl.download_and_extract(name, group, force=False)
            if not os.path.isdir(dataset_dir):
                sys.exit(f"  [skip] {name}: download/extract failed")

            cvt.process_dir(dataset_dir)
            tns_path = os.path.join(dataset_dir, f"{name}.tns")
            if not os.path.isfile(tns_path):
                sys.exit(f"  [skip] {name}: conversion failed, no .tns produced")

            shutil.copyfile(tns_path, TENSOR_B)
            shutil.copyfile(tns_path, TENSOR_D)

            n = entry["num_rows"]  # square: num_rows == num_cols
            print(f"  [generate] dense tensor_C ({n} x {n}) ...")
            generate_dense_2d_tns(TENSOR_C, n, n)

            print("  [run] splyce phase_001 ...")
            splyce_times, splyce_timed_out = run_binary(SPLYCE_BIN, timeout)

            if splyce_timed_out:
                print("  [skip] splyce timed out — skipping baseline run")
                scf_times, scf_med = None, "SKIPPED"
            else:
                print("  [run] baseline (scf) ...")
                scf_times, _ = run_binary(BASELINE_BIN, timeout * 5)
                scf_med = median_excl_first(scf_times) if scf_times else "NA"

            for i, t in enumerate(splyce_times or []):
                raw_writer.writerow([name, "splyce_phase_001", i, t])
            for i, t in enumerate(scf_times or []):
                raw_writer.writerow([name, "scf", i, t])
            rf.flush()

            splyce_med = median_excl_first(splyce_times) if splyce_times else "NA"

            if splyce_med != "NA":
                summary_writer.writerow([name, group, entry["nnz"], scf_med, splyce_med])
            sf.flush()
            print(f"  scf_median={scf_med}  splyce_median={splyce_med}")

        finally:
            for f in (TENSOR_B, TENSOR_C, TENSOR_D):
                if os.path.isfile(f):
                    os.remove(f)
            if os.path.isdir(dataset_dir):
                shutil.rmtree(dataset_dir)

    print(f"Done. Summary: {SUMMARY_CSV}")
    print(f"Raw backup: {RAW_BACKUP_CSV}")


if __name__ == "__main__":
    main()
